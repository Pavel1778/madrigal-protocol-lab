"""Build a standalone, editable team slide as its own PPTX.

The deck's slide 2 is generated by ``presentation.scripts.build_pptx`` together
with the other eighteen. This script produces a *separate* two-slide file — one
dark, one light — whose text and photo a teammate can edit in PowerPoint without
touching the generator. The text is native (no picture of text), the photo is a
replaceable picture placeholder, and the fonts fall back to the system if the
bundled ones are absent.

    python -m presentation.make_team_slide
"""

from __future__ import annotations

from pathlib import Path

from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.enum.shapes import MSO_SHAPE
from pptx.enum.text import MSO_ANCHOR, PP_ALIGN
from pptx.util import Inches, Pt

PRES = Path(__file__).resolve().parent
OUT = PRES / "team-slide.pptx"
AVATARS = {
    "Сабадаш Павел": PRES / "public" / "avatar_pavel_round.png",
    "Предков Никита": PRES / "public" / "avatar_nikita_round.png",
}

SLIDE_W = Inches(13.333)
SLIDE_H = Inches(7.5)

PALETTES = {
    "Тёмная": dict(bg=RGBColor(0x13, 0x15, 0x16), surface=RGBColor(0x1D, 0x1D, 0x1D),
                   text=RGBColor(0xED, 0xED, 0xED), secondary=RGBColor(0xB8, 0xB8, 0xB8),
                   accent=RGBColor(0xA2, 0x39, 0x1D)),
    "Светлая": dict(bg=RGBColor(0xFA, 0xFA, 0xFA), surface=RGBColor(0xFF, 0xFF, 0xFF),
                    text=RGBColor(0x16, 0x18, 0x1A), secondary=RGBColor(0x4A, 0x4A, 0x4A),
                    accent=RGBColor(0xB7, 0x30, 0x1A)),
}

MEMBERS = [
    ("Сабадаш Павел", "Архитектура · захват · интерфейс", "@Pasha1778",
     "qr_telegram_pasha.png"),
    ("Предков Никита", "Правила · тесты · ревью", "@petruan",
     "qr_telegram_nikita.png"),
]

F_HEAD = "Montserrat"
F_BODY = "Montserrat"
F_MONO = "JetBrains Mono"


def _rect(slide, x, y, w, h, color, shape=MSO_SHAPE.RECTANGLE):
    box = slide.shapes.add_shape(shape, x, y, w, h)
    box.fill.solid()
    box.fill.fore_color.rgb = color
    box.line.fill.background()
    box.shadow.inherit = False
    return box


def _text(slide, x, y, w, h, anchor=MSO_ANCHOR.TOP):
    box = slide.shapes.add_textbox(x, y, w, h)
    tf = box.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    return box, tf


def _line(tf, text, size, color, bold=False, font=F_BODY, align=PP_ALIGN.LEFT,
          first=False, space_after=0):
    p = tf.paragraphs[0] if first else tf.add_paragraph()
    p.alignment = align
    p.space_after = Pt(space_after)
    run = p.add_run()
    run.text = text
    run.font.size = Pt(size)
    run.font.name = font
    run.font.bold = bold
    run.font.color.rgb = color
    return p


def _slide(prs, palette, title):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    _rect(slide, 0, 0, SLIDE_W, SLIDE_H, palette["bg"])
    _rect(slide, 0, 0, Inches(0.08), SLIDE_H, palette["accent"])

    box, tf = _text(slide, Inches(0.9), Inches(0.6), Inches(11.5), Inches(0.9))
    _line(tf, title, 34, palette["text"], bold=True, font=F_HEAD, first=True)

    _, tf2 = _text(slide, Inches(0.9), Inches(1.35), Inches(11.5), Inches(0.4))
    _line(tf2, "UMIRHack 2026 · кейс #02 · Мадригал", 15, palette["secondary"], first=True)

    top = Inches(2.3)
    for i, (name, role, handle, qr) in enumerate(MEMBERS):
        y = top + i * Inches(1.9)
        _rect(slide, Inches(0.9), y, Inches(11.5), Inches(1.6), palette["surface"])
        avatar = AVATARS.get(name)
        if avatar is not None and avatar.is_file():
            slide.shapes.add_picture(str(avatar), Inches(1.2), y + Inches(0.15),
                                     height=Inches(1.3))
        tx = Inches(2.9)
        _, t1 = _text(slide, tx, y + Inches(0.18), Inches(7.0), Inches(0.6))
        _line(t1, name, 26, palette["text"], bold=True, font=F_HEAD, first=True)
        _, t2 = _text(slide, tx, y + Inches(0.72), Inches(7.0), Inches(0.4))
        _line(t2, role, 15, palette["secondary"], first=True)
        _, t3 = _text(slide, tx, y + Inches(1.08), Inches(7.0), Inches(0.4))
        _line(t3, handle, 14, palette["accent"], font=F_MONO, first=True)
        qr_path = PRES / "public" / qr
        if qr_path.is_file():
            slide.shapes.add_picture(str(qr_path), Inches(11.0), y + Inches(0.18),
                                     height=Inches(1.25))

    _, foot = _text(slide, Inches(0.9), Inches(6.7), Inches(11.5), Inches(0.5))
    _line(foot, "github.com/Pavel1778/madrigal-protocol-lab", 13,
          palette["secondary"], font=F_MONO, first=True)
    return slide


def main() -> int:
    prs = Presentation()
    prs.slide_width = SLIDE_W
    prs.slide_height = SLIDE_H
    for title, palette in PALETTES.items():
        _slide(prs, palette, f"Нас двое — {title.lower()} тема")
    prs.save(str(OUT))
    print(f"wrote {OUT} ({len(prs.slides)} slides)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
